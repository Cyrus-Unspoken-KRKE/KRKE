"""Execute the six competency questions locally and write readable results."""
from pathlib import Path
from rdflib import Graph

ROOT = Path(__file__).resolve().parents[1]
g = Graph().parse(ROOT / "output" / "combined.ttl", format="turtle")
lines = ["# SPARQL results", "", "Generated by `python src/run_queries.py` from `output/combined.ttl`.", ""]
for path in sorted((ROOT / "queries").glob("*.sparql")):
    result = g.query(path.read_text(encoding="utf-8"))
    lines += [f"## {path.name}", "", f"Rows: {len(result)}", ""]
    headers = [str(var) for var in result.vars]
    lines += ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in result:
        values = [str(value or "").replace("|", "\\|").replace("\n", " ") for value in row]
        lines.append("| " + " | ".join(values) + " |")
    lines.append("")
(ROOT / "output" / "query_results.md").write_text("\n".join(lines), encoding="utf-8")
print("Ran 6 queries; see output/query_results.md")
